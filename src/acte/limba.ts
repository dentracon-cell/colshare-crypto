export type Limba = "en" | "ro" | "de" | "fr" | "es" | "it" | "pl" | "nl" | "pt" | "uk";
export const LIMBI: Record<Limba, string> = {
  en: "English", de: "Deutsch", es: "Español", fr: "Français", it: "Italiano", nl: "Nederlands", pl: "Polski", pt: "Português", ro: "Română", uk: "Українська",
};
/** The languages a person reviewed (EN, RO, DE, FR); the others are translated from English, to be read by a native speaker. */
export const LIMBI_VERIFICATE: Limba[] = ["en", "ro", "de", "fr"];
/** Each language's locale, for dates. */
export const LOCALE: Record<Limba, string> = { en: "en-GB", ro: "ro-RO", de: "de-DE", fr: "fr-FR", es: "es-ES", it: "it-IT", pl: "pl-PL", nl: "nl-NL", pt: "pt-PT", uk: "uk-UA" };
const TABELE: Record<Limba, Record<Cheie, string>> = { en: EN, ro: RO, de: DE, fr: FR, es: ES, it: IT, pl: PL, nl: NL, pt: PT, uk: UK };

/** The phone's language, when it is one of ours; English otherwise. */
export function limbaTelefonului(): Limba {
  const l = (globalThis.navigator?.language ?? "").slice(0, 2).toLowerCase();
  return l in TABELE ? l as Limba : "en";
}

/** A language a link names in its path (<domain>/a/ro/#…, /p/de/#…): the one its maker chose for the recipient. */
export function limbaLinkului(cale: string): Limba | undefined {
  const l = /^\/[ap]\/([a-z]{2})\/?$/.exec(cale)?.[1];
  return l && l in TABELE ? l as Limba : undefined;
}
/** A link page's language: the link's, else the phone's. */
export const limbaPaginii = () => limbaLinkului(globalThis.location?.pathname ?? "") ?? limbaTelefonului();

let limba: Limba = limbaTelefonului();
export const limbaCurenta = () => limba;
export function punLimba(l: Limba): void {
  limba = l;
  if (globalThis.document) document.documentElement.lang = l;
}

const umple = (s: string, valori: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (m, n: string) => (n === "app" ? aplicatie.nume : n in valori ? String(valori[n]) : m));

/** The string `k` in the current language, with {app} and the values given put in. */
/** A text in every language, to recognise a name the program wrote in another one. */
export const inToate = (k: Cheie): string[] => Object.values(TABELE).map((x) => x[k]);

export function t(k: Cheie, valori: Record<string, string | number> = {}): string {
  return umple(TABELE[limba][k], valori);
}

/**
 * The plural forms a language needs besides `unu` (exactly 1) and the `multe` key itself, by the `multe` key and the
 * Intl.PluralRules category: Polish and Ukrainian say 2–4 one way and 5–20 another (and Ukrainian 21 like 1).
 * Optional: a count with no form here takes the `multe` text, which those tables word to fit any count.
 */
export type FormePlural = Partial<Record<Cheie, Partial<Record<Intl.LDMLPluralRule, string>>>>;
const FORME: Partial<Record<Limba, FormePlural>> = { pl: PL_FORME, uk: UK_FORME };
const reguli = new Map<Limba, Intl.PluralRules>();
const categorie = (n: number): Intl.LDMLPluralRule => {
  // Very old WebViews (Android 7 without updates) have no PluralRules: the `multe` text then.
  if (typeof Intl.PluralRules !== "function") return "other";
  let r = reguli.get(limba);
  if (!r) reguli.set(limba, (r = new Intl.PluralRules(LOCALE[limba])));
  return r.select(n);
};
/** Romanian puts "de" between a count and its noun from 20 up: 19 acte, 20 de acte, 101 acte, 120 de acte (as core/ro-format cate()). */
const cuDe = (n: number) => { const rest = Math.abs(n) % 100; return rest >= 20 || (n >= 20 && rest === 0); };

/** `unu` for exactly one; otherwise the form the language uses for that count (`multe`, or one from FORME), with {n}. */
export function nr(n: number, unu: Cheie, multe: Cheie, valori: Record<string, string | number> = {}): string {
  const v = { ...valori, n: limba === "ro" && cuDe(n) ? `${n} de` : n };
  if (n === 1) return t(unu, v);
  const forma = FORME[limba]?.[multe]?.[categorie(n)];
  return forma === undefined ? t(multe, v) : umple(forma, v);
}

/** The plural forms, for the tests. */
export const _forme = FORME;

/** Every table has every key, and the same {values}: for the tests. */
export const _tabele = TABELE;

/**
 * The ask's chips ("ID card", "Passport"…) travel as their keys, "#buletin", so the person asked reads them in their
 * own language (launch audit 2026-10-21, U7). Words typed travel as typed; asks made before carry words, shown as they
 * are. `cheieCerut` gives a chip's key for its words in any language, `numeCerut` the words for the reader.
 */
const CIPURI = ["buletin", "pasaport", "fluturasi", "domiciliu", "contract", "extras"] as const;
export function cheieCerut(x: string): string {
  const k = CIPURI.find((c) => Object.values(TABELE).some((tb) => tb[`cer.c.${c}`] === x));
  return k ? `#${k}` : x;
}
export function numeCerut(x: string): string {
  const m = /^#([a-z]+)$/.exec(x);
  return m && (CIPURI as readonly string[]).includes(m[1]) ? t(`cer.c.${m[1]}` as Cheie) : x;
}

/** A date as the reader's language writes it. */
export const data = (iso: string) => new Date(iso).toLocaleDateString(LOCALE[limba], { day: "numeric", month: "long", year: "numeric" });
